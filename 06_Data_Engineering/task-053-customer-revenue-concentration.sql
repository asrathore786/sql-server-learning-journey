WITH RevenueByCustomer AS
(
SELECT
	O.CustomerID,
	SUM(O.TotalAmount) AS CustomerRevenue
FROM Orders O
GROUP BY
	O.CustomerID
),
Ranking_Revenue AS
(
SELECT
	R.CustomerID,
	R.CustomerRevenue,
	ROW_NUMBER() OVER(ORDER BY R.CustomerRevenue DESC, R.CustomerID ASC) AS RevenueRank,
	SUM(R.CustomerRevenue) OVER(ORDER BY R.CustomerRevenue DESC, R.CustomerID ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW) AS RevenueTotal,
	SUM(R.CustomerRevenue) OVER() AS CompanyTotal
FROM RevenueByCustomer R
)

SELECT 
	RR.CustomerID,
	RR.CustomerRevenue,
	RR.RevenueTotal,
	RR.RevenueRank,
	RR.CompanyTotal,
	CAST(
		RR.RevenueTotal * 100 
			/ RR.CompanyTotal
		AS DECIMAL(10,2)) AS CumulativeRevenuePct
FROM Ranking_Revenue RR
ORDER BY 
	RR.RevenueRank

