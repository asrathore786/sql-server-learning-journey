### Business requirement

The finance team wants to measure how much of the company's total revenue is generated by its highest-revenue customers.

Write a SQL query that calculates each customer's revenue, ranks customers from highest to lowest revenue, and determines the   revenue contributed by customers up to and including each customer's rank.

Return exactly these columns:

| Column                 | Description                                           |
| ---------------------- | ----------------------------------------------------- |
| `CustomerID`           | Customer identifier                                   |
| `CustomerRevenue`      | Total revenue generated by the customer               |
| `RevenueRank`          | Customer's rank by revenue                            |
| `CumulativeRevenue`    | Running total of customer revenue in rank order       |
| `CumulativeRevenuePct` | Cumulative revenue as a percentage of overall revenue |

### Business rules

1. Use `TotalAmount` from `dbo.Orders` as the revenue measure.
2. Include every customer who has at least one order.
3. Rank customers by revenue descending, breaking ties with `CustomerID` ascending.
4. Calculate cumulative revenue in the same order as the ranking.
5. Calculate cumulative revenue percentage against the overall revenue.
6. Round the percentage to two decimal places.
7. Return results ordered by `RevenueRank` ascending.
8. Use read-only SQL. CTEs and window functions are permitted; do not create temporary or permanent tables.

Your turn: Write the query independently and run it in SSMS. I won't provide hints about grain, query structure, or functions before you attempt it. I'll review your SQL first, then validate the output you share.

